export const ROLE_KEYS = ["data_eval", "agent_env", "post_training"] as const;
export type RoleKey = (typeof ROLE_KEYS)[number];

export const templateTaskSchema = z.object({
  key: z
    .string()
    .regex(/^w\d{2}-(mon|tue|wed|thu|fri|sat|sun)(-review)?$/, "routine key")
    .or(z.string().regex(/^pt-w\d{1,2}-[a-z0-9-]+$/, "post-training key")),
  week: z.number().int().min(1).max(14),
  day: z.enum(["mon", "tue", "wed", "thu", "fri", "sat", "sun"]),
  category: z.enum(["deep_work", "practice", "application", "review"]),
  minutes: z.number().int().positive(),
  title: z.string().min(1),
  roles: z.array(z.enum(ROLE_KEYS)).min(1),
  project: z.enum(["evalops", "rollout_lab", "post_training_lab"]).optional(),
  fixedDeadline: z.boolean().default(false),
  optionalTrack: z.boolean().default(false),
  swapGroup: z.literal("post_training").optional(),
});

export const milestoneSchema = z.object({
  key: z.string().regex(/^p[123]-m\d$/),
  title: z.string().min(1),
  acceptance: z.string().min(1),
  targetDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  isCompletionGate: z.boolean(),
  sortOrder: z.number().int().min(0),
});

export const projectSchema = z.object({
  key: z.enum(["evalops", "rollout_lab", "post_training_lab"]),
  name: z.string().min(1),
  targetRoles: z.array(z.enum(ROLE_KEYS)).min(1),
  budgetMinutes: z.number().int().positive(),
  state: z.enum(["locked", "active", "completed", "at_risk"]),
  purpose: z.string().min(1),
  milestones: z.array(milestoneSchema).min(1),
});

export const gateSchema = z.object({
  role: z.enum(ROLE_KEYS),
  key: z.string().min(1),
  title: z.string().min(1),
});

export const templateV1Schema = z.object({
  version: z.literal(1),
  windowStart: z.string(),
  windowEnd: z.string(),
  weeks: z.array(templateWeekSchema).length(14),
  tasks: z.array(templateTaskSchema),
  projects: z.array(projectSchema).length(3),
  gates: z.array(gateSchema),
});

export type TemplateWeek = z.infer<typeof templateWeekSchema>;
export type TemplateTask = z.infer<typeof templateTaskSchema>;
export type TemplateTaskInput = z.input<typeof templateTaskSchema>;
export type TemplateProject = z.infer<typeof projectSchema>;
export type TemplateGate = z.infer<typeof gateSchema>;
export type TemplateV1 = z.infer<typeof templateV1Schema>;

