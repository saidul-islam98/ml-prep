/** Deterministic content digest over the canonical template shape. */
export async function templateContentDigest(): Promise<string> {
  const canonical = {
    weeks: TEMPLATE_V1.weeks,
    tasks: TEMPLATE_V1.tasks.map((t) => ({ ...t, date: taskDate(t) })),
    projects: TEMPLATE_V1.projects,
    gates: TEMPLATE_V1.gates,
  };
  const bytes = new TextEncoder().encode(JSON.stringify(canonical));
  const hash = await crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(hash))
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

