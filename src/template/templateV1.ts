/** Derive each task's exact scheduled date from its week and weekday. */
export function taskDate(task: TemplateTask): string {
  const week = RAW_WEEKS.find((w) => w.week === task.week);
  if (!week) throw new Error(`Unknown week ${task.week}`);
  return isoDate(week.start, task.day);
}

