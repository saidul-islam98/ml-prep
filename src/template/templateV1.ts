const DAY_OFFSET: Record<TemplateTask["day"], number> = {
  mon: 0,
  tue: 1,
  wed: 2,
  thu: 3,
  fri: 4,
  sat: 5,
  sun: 6,
};

function isoDate(weekStart: string, day: TemplateTask["day"]): string {
  const start = new Date(`${weekStart}T12:00:00Z`);
  start.setUTCDate(start.getUTCDate() + DAY_OFFSET[day]);
  return start.toISOString().slice(0, 10);
}

